FLASK_PREFIX = "/en/stable"


class FlaskCtx:
    """Global state for one Flask build (labels, python inventory, current page)."""
    labels: dict[str, tuple[str, str]] = {}     # label -> (url#id, title)
    pages: dict[str, tuple[str, str]] = {}      # docname -> (url, title)
    inventory: dict[str, str] = {}              # flask.Flask.route -> url#id
    current_doc: str = ""
    current_module: str = "flask"
    si: SourceIndex | None = None


CTX = FlaskCtx()


def doc_url(docname: str) -> str:
    if docname == "index":
        return FLASK_PREFIX + "/"
    if docname.endswith("/index"):
        return f"{FLASK_PREFIX}/{docname[:-6]}/"
    return f"{FLASK_PREFIX}/{docname}/"


def resolve_doc(target: str) -> str:
    if target.startswith("/"):
        return target.lstrip("/")
    base = CTX.current_doc.rsplit("/", 1)[0] if "/" in CTX.current_doc else ""
    return os.path.normpath(os.path.join(base, target)).replace("\\", "/")


def _split_title(text):
    m = re.match(r"^(.*?)\s*<([^>]+)>$", text, re.S)
    return (m.group(1), m.group(2)) if m else (None, text)


def role_doc(name, rawtext, text, lineno, inliner, options={}, content=[]):
    title, target = _split_title(text)
    if ":" in target:  # intersphinx, e.g. werkzeug:test -> external docs
        proj, _, path = target.partition(":")
        url = f"https://{proj}.palletsprojects.com/en/stable/{path.strip('/')}/"
        return [nodes.reference(rawtext, title or path, refuri=url, classes=["reference", "external"])], []
    dn = resolve_doc(target)
    url, ptitle = CTX.pages.get(dn, (doc_url(dn), dn))
    node = nodes.reference(rawtext, title or ptitle, refuri=url, classes=["reference", "internal"])
    return [node], []


def role_ref(name, rawtext, text, lineno, inliner, options={}, content=[]):
    title, target = _split_title(text)
    if target in CTX.labels:
        url, ltitle = CTX.labels[target]
        return [nodes.reference(rawtext, title or ltitle, refuri=url, classes=["reference", "internal"])], []
    return [nodes.emphasis(rawtext, title or target)], []


def lookup_py(target: str) -> tuple[str, str | None]:
    t = target.lstrip("~!").rstrip("()")
    display = t.split(".")[-1] if target.startswith("~") else t.lstrip(".")
    if t.startswith("."):
        t = t[1:]
        cands = [k for k in CTX.inventory if k.endswith("." + t)]
        return display, CTX.inventory[sorted(cands, key=len)[0]] if cands else None
    for full in (t, f"{CTX.current_module}.{t}", f"flask.{t}"):
        if full in CTX.inventory:
            return display, CTX.inventory[full]
    cands = [k for k in CTX.inventory if k.endswith("." + t)]
    return display, CTX.inventory[sorted(cands, key=len)[0]] if cands else None


def role_py(name, rawtext, text, lineno, inliner, options={}, content=[]):
    title, target = _split_title(text)
    display, url = lookup_py(target)
    if name in ("func", "meth") and not display.endswith(")"):
        display += "()"
    lit = nodes.literal(rawtext, title or display, classes=["xref", "py"])
    if url:
        ref = nodes.reference("", "", lit, refuri=url, classes=["reference", "internal"])
        return [ref], []
    return [lit], []


