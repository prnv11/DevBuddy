class CodeBlock(Directive):
    optional_arguments = 1
    has_content = True
    option_spec = {"caption": directives.unchanged, "emphasize-lines": directives.unchanged,
                   "linenos": directives.flag, "force": directives.flag}

    def run(self):
        lang = self.arguments[0] if self.arguments else "python"
        code = "\n".join(self.content)
        raw = (f'<div class="highlight-{lang} notranslate"><div class="highlight"><pre>'
               f"{html.escape(code)}</pre></div></div>")
        return [nodes.raw("", raw, format="html")]


class Noop(Directive):
    optional_arguments = 10
    final_argument_whitespace = True
    has_content = True
    option_spec = None

    def run(self):
        return []


Noop.option_spec = {k: directives.unchanged for k in
                    ("maxdepth", "hidden", "caption", "glob", "titlesonly", "class", "members",
                     "inherited-members", "exclude-members", "noindex", "language", "alt", "align",
                     "width", "height", "scale", "target", "start-after", "end-before", "linenos")}


class Container(Directive):
    """tabs / tab / group-tab / rst-class / only -> parse content in a div."""
    optional_arguments = 10
    final_argument_whitespace = True
    has_content = True
    option_spec = Noop.option_spec

    def run(self):
        node = nodes.container()
        if self.arguments and self.name in ("tab", "group-tab", "code-tab"):
            node += nodes.paragraph(text=" ".join(self.arguments), classes=["tab-title"])
        self.state.nested_parse(self.content, self.content_offset, node)
        return [node]


class VersionNote(Directive):
    required_arguments = 1
    final_argument_whitespace = True
    has_content = True

    def run(self):
        label = {"versionadded": "Added in version", "versionchanged": "Changed in version",
                 "deprecated": "Deprecated since version"}[self.name]
        node = nodes.container(classes=[self.name])
        para = nodes.paragraph()
        para += nodes.emphasis(text=f"{label} {self.arguments[0]}: ")
        node += para
        self.state.nested_parse(self.content, self.content_offset, node)
        return [node]


class Toctree(Directive):
    has_content = True
    option_spec = Noop.option_spec

    def run(self):
        lst = nodes.bullet_list(classes=["toctree"])
        for line in self.content:
            line = line.strip()
            if not line or line.startswith(":"):
                continue
            title, target = _split_title(line)
            dn = resolve_doc(target)
            url, ptitle = CTX.pages.get(dn, (doc_url(dn), dn))
            item = nodes.list_item()
            para = nodes.paragraph()
            para += nodes.reference("", title or ptitle, refuri=url, classes=["reference", "internal"])
            item += para
            lst += item
        return [nodes.compound("", lst, classes=["toctree-wrapper"])]


class CurrentModule(Directive):
    required_arguments = 1
    option_spec = Noop.option_spec

    def run(self):
        CTX.current_module = self.arguments[0]
        return []


def py_object_html(objtype: str, fullname: str, sig: str, doc: str) -> str:
    return (f'<dl class="py {objtype}"><dt class="sig sig-object py" id="{fullname}">'
            f'<em class="property">{objtype} </em><span class="sig-name descname">{html.escape(sig)}</span>'
            f'<a class="headerlink" href="#{fullname}">¶</a></dt><dd>{rst_fragment(doc)}</dd></dl>')


def rst_fragment(doc: str) -> str:
    if not doc.strip():
        return ""
    try:
        return publish_parts(doc, writer_name="html5",
                             settings_overrides={"report_level": 5, "halt_level": 5,
                                                 "doctitle_xform": False, "initial_header_level": 4,
                                                 "syntax_highlight": "none"})["body"]
    except Exception:
        return f"<p>{html.escape(doc)}</p>"


class PyObject(Directive):
    """py:data / data / function / class / attribute / method / module."""
    required_arguments = 1
    final_argument_whitespace = True
    has_content = True
    option_spec = Noop.option_spec

    def run(self):
        objtype = self.name.split(":")[-1]
        if objtype == "module":
            CTX.current_module = self.arguments[0]
            return []
        sig = self.arguments[0]
        bare = sig.split("(")[0].strip()
        full = bare if bare.startswith(CTX.current_module + ".") else f"{CTX.current_module}.{bare}"
        node = nodes.container()
        self.state.nested_parse(self.content, self.content_offset, node)
        # render children by writing a minimal doc around them
        inner = nodes.raw("", f'<dl class="py {objtype}"><dt class="sig sig-object py" id="{full}">'
                              f'<em class="property">{objtype} </em><span class="sig-name descname">{html.escape(sig)}</span></dt><dd>',
                          format="html")
        return [inner, node, nodes.raw("", "</dd></dl>", format="html")]


class AutoObject(Directive):
    required_arguments = 1
    has_content = True
    option_spec = Noop.option_spec

    def run(self):
        objtype = self.name.replace("auto", "")
        name = self.arguments[0]
        full = name if "." in name else f"{CTX.current_module}.{name}"
        r = CTX.si.find(full) if CTX.si else None
        if r is None:
            return []
        node, mod, f = r
        sig = node_signature(full.split(".")[-1], node) if objtype == "function" else full.split(".")[-1]
        parts = [py_object_html("class" if objtype == "class" else objtype, full, sig, node_doc(node))]
        if objtype == "class" and "members" in self.options:
            inherited = "inherited-members" in self.options
            excl = set((self.options.get("exclude-members") or "").replace(",", " ").split())
            mem = CTX.si.members(node, mod, f, inherited)
            for mname, (mnode, _, _) in mem.items():
                if mname in excl:
                    continue
                d = node_doc(mnode)
                if not d:
                    continue
                kind = "property" if is_property(mnode) or isinstance(mnode, tuple) else "method"
                sig = mname if kind == "property" else node_signature(mname, mnode)
                parts.append(py_object_html(kind, f"{full}.{mname}", sig, d))
        return [nodes.raw("", "".join(parts), format="html")]


def register_flask_directives():
    for d in ("code-block", "sourcecode", "code"):
        directives.register_directive(d, CodeBlock)
    for d in ("tabs", "tab", "group-tab", "code-tab", "rst-class", "only", "container"):
        directives.register_directive(d, Container)
    for d in ("versionadded", "versionchanged", "deprecated"):
        directives.register_directive(d, VersionNote)
    directives.register_directive("toctree", Toctree)
    directives.register_directive("currentmodule", CurrentModule)
    directives.register_directive("py:currentmodule", CurrentModule)
    for d in ("data", "function", "class", "attribute", "method", "module", "exception", "decorator",
              "py:data", "py:function", "py:class", "py:attribute", "py:method", "py:module", "py:exception"):
        directives.register_directive(d, PyObject)
    for d in ("autoclass", "autofunction", "autodata", "autoexception", "automodule"):
        directives.register_directive(d, AutoObject)
    for d in ("literalinclude", "include", "image", "figure", "seealso", "glossary", "index",
              "highlight", "testsetup", "doctest", "tabularcolumns"):
        directives.register_directive(d, Noop)
    directives.register_directive("seealso", Container)


def flask_prepass(docs: Path, rst_files: list[Path]):
    for f in rst_files:
        dn = f.relative_to(docs).with_suffix("").as_posix()
        text = f.read_text(encoding="utf-8")
        lines = text.split("\n")
        title = dn
        for i in range(len(lines) - 1):
            if lines[i].strip() and re.fullmatch(r"([=\-~^*#\"])\1{2,}", lines[i + 1].strip() or "x") \
                    and len(lines[i + 1].strip()) >= len(lines[i].strip()) - 1:
                title = lines[i].strip().replace("``", "")
                break
        url = doc_url(dn)
        CTX.pages[dn] = (url, title)
        for i, line in enumerate(lines):
            m = re.match(r"^\.\. _([\w\-. ]+):\s*$", line)
            if m:
                label = m.group(1)
                ltitle = label
                for j in range(i + 1, min(i + 6, len(lines) - 1)):
                    if lines[j].strip() and not lines[j].startswith(".."):
                        ltitle = lines[j].strip()
                        break
                CTX.labels[label] = (f"{url}#{nodes.make_id(label)}", ltitle)
        # python inventory
        module = "flask"
        for line in lines:
            m = re.match(r"^\.\. (?:py:)?(?:current)?module::\s*(\S+)", line)
            if m:
                module = m.group(1)
            m = re.match(r"^\.\. (?:py:)?(auto)?(class|function|data|attribute|exception|method)::\s*([\w.]+)", line)
            if m:
                name = m.group(3)
                full = name if name.startswith(module + ".") or name.startswith("flask.") else f"{module}.{name}"
                CTX.inventory.setdefault(full, f"{url}#{full}")
                if m.group(1) and m.group(2) == "class" and CTX.si:
                    r = CTX.si.find(full)
                    if r and isinstance(r[0], ast.ClassDef):
                        for mname in CTX.si.members(r[0], r[1], r[2], True):
                            CTX.inventory.setdefault(f"{full}.{mname}", f"{url}#{full}.{mname}")


FLASK_SKIP = {"changes", "license", "contributing"}


def build_flask(repo: Path, out: Path):
    docs = repo / "docs"
    CTX.si = SourceIndex({"flask": repo / "src" / "flask"})
    register_flask_directives()
    rst_files = [f for f in sorted(docs.rglob("*.rst"))
                 if not any(p.startswith("_") for p in f.relative_to(docs).parts)
                 and f.relative_to(docs).with_suffix("").as_posix() not in FLASK_SKIP]
    # api.rst first so cross-references prefer the API reference page
    flask_prepass(docs, sorted(rst_files, key=lambda f: f.name != "api.rst"))
    nav = "".join(f'<li class="toctree-l1"><a class="reference internal" href="{CTX.pages[d][0]}">'
                  f"{html.escape(CTX.pages[d][1])}</a></li>"
                  for d in sorted(CTX.pages, key=lambda d: (d.count("/"), d)))
    n = 0
    for f in rst_files:
        dn = f.relative_to(docs).with_suffix("").as_posix()
        CTX.current_doc, CTX.current_module = dn, "flask"
        url, title = CTX.pages[dn]
        parts = publish_parts(f.read_text(encoding="utf-8"), writer_name="html5",
                              settings_overrides={"report_level": 5, "halt_level": 5,
                                                  "doctitle_xform": False, "syntax_highlight": "none",
                                                  "initial_header_level": 1})
        body = parts["body"]
        rel = url[len(FLASK_PREFIX):]
        page = FLASK_TEMPLATE.format(title=html.escape(title), path=url, nav=nav, body=body, rel=rel)
        dest = out / "flask" / url.strip("/") / "index.html"
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(page, encoding="utf-8")
        n += 1
    (out / "flask" / "robots.txt").write_text(
        "User-agent: *\nDisallow: /en/stable/_sources/\nDisallow: /en/stable/search/\n"
        "Sitemap: https://flask.palletsprojects.com/sitemap.xml\n")
    print(f"flask: {n} pages, {len(CTX.labels)} labels, {len(CTX.inventory)} api objects")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--fastapi", type=Path, required=True)
    ap.add_argument("--flask", type=Path, required=True)
    ap.add_argument("--out", type=Path, default=Path("mirror"))
    a = ap.parse_args()
    build_fastapi(a.fastapi, a.out)
    build_flask(a.flask, a.out)
