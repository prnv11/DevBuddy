"""
Build a static HTML mirror of the FastAPI and Flask documentation from their
source repositories, so the crawler can be exercised offline.

Why this exists
---------------
The live sites (fastapi.tiangolo.com, flask.palletsprojects.com) are the real
crawl targets and `ir/crawler.py` works against them unchanged. This tool is
only for environments where those hosts cannot be reached: it renders the
Markdown / reStructuredText sources into HTML that mimics the *structure* of
the live themes (Material for MkDocs and the Pallets Sphinx theme):

  * the same URL scheme (/tutorial/first-steps/, /en/stable/quickstart/),
  * a full navigation sidebar, header and footer (boilerplate the crawler
    must strip before extracting content links),
  * <pre><code> blocks, heading anchors, Sphinx-style API object <dl>s,
  * a version switcher and a search link (spider traps the crawler must skip).

The sources are treated purely as data: nothing from the repositories is
imported or executed. API reference pages (Sphinx autodoc / mkdocstrings) are
generated by reading docstrings with `ast`.

Usage:
    git clone --depth 1 https://github.com/fastapi/fastapi.git /tmp/fa
    git clone --depth 1 https://github.com/pallets/flask.git  /tmp/fl
    python tools/build_mirror.py --fastapi /tmp/fa --flask /tmp/fl --out mirror/
    python tools/serve_mirror.py mirror/      # two local "hosts"
"""
