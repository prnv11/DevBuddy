class SourceIndex:
    """Locate classes / functions / attributes by dotted name using ast."""

    def __init__(self, roots: dict[str, Path]):
        self.roots = roots            # top-level package -> directory
        self._cache: dict[Path, ast.Module] = {}

    def module_file(self, modname: str) -> Path | None:
        top, *rest = modname.split(".")
        root = self.roots.get(top)
        if root is None:
            spec = importlib.util.find_spec(top)  # locate only, does not import
            if spec is None or not spec.submodule_search_locations:
                return None
            root = Path(list(spec.submodule_search_locations)[0])
            self.roots[top] = root
        p = root.joinpath(*rest)
        if (p / "__init__.py").exists():
            return p / "__init__.py"
        if p.with_suffix(".py").exists():
            return p.with_suffix(".py")
        return None

    def parse(self, f: Path) -> ast.Module:
        if f not in self._cache:
            self._cache[f] = ast.parse(f.read_text(encoding="utf-8"))
        return self._cache[f]

    def _resolve_relative(self, modname: str, f: Path, node: ast.ImportFrom) -> str:
        if node.level == 0:
            return node.module or ""
        base = modname.split(".")
        if f.name != "__init__.py":
            base = base[:-1]
        base = base[: len(base) - (node.level - 1)] if node.level > 1 else base
        return ".".join(base + ([node.module] if node.module else []))

    def find(self, dotted: str, depth: int = 0):
        """Return (node, modname, file) for a dotted object name."""
        if depth > 8:
            return None
        parts = dotted.split(".")
        for i in range(len(parts) - 1, 0, -1):
            modname = ".".join(parts[:i])
            f = self.module_file(modname)
            if f is None:
                continue
            obj = self._find_in_module(modname, f, parts[i], depth)
            if obj is None:
                continue
            node, m, ff = obj
            for attr in parts[i + 1:]:
                if not isinstance(node, ast.ClassDef):
                    return None
                sub = self.class_member(node, m, ff, attr)
                if sub is None:
                    return None
                node, m, ff = sub
            return node, m, ff
        return None

    def _find_in_module(self, modname, f, name, depth):
        mod = self.parse(f)
        for node in mod.body:
            if isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == name:
                return node, modname, f
            if isinstance(node, (ast.Assign, ast.AnnAssign)):
                targets = node.targets if isinstance(node, ast.Assign) else [node.target]
                if any(isinstance(t, ast.Name) and t.id == name for t in targets):
                    return node, modname, f
        for node in ast.walk(mod):
            if isinstance(node, ast.ImportFrom):
                for a in node.names:
                    if (a.asname or a.name) == name:
                        src = self._resolve_relative(modname, f, node)
                        return self.find(f"{src}.{a.name}", depth + 1)
        return None

    def bases(self, cls: ast.ClassDef, modname: str, f: Path):
        out = []
        mod = self.parse(f)
        imports = {}
        for node in ast.walk(mod):
            if isinstance(node, ast.ImportFrom):
                for a in node.names:
                    imports[a.asname or a.name] = f"{self._resolve_relative(modname, f, node)}.{a.name}"
        for b in cls.bases:
            name = ast.unparse(b)
            if name in ("object", "Generic") or name.startswith(("t.Generic", "Generic[")):
                continue
            if "." in name:
                head, tail = name.split(".", 1)
                full = f"{imports.get(head, head)}.{tail}"
            else:
                full = imports.get(name, f"{modname}.{name}")
            r = self.find(full)
            if r and isinstance(r[0], ast.ClassDef):
                out.append(r)
        return out

    def class_member(self, cls, modname, f, attr, seen=None):
        seen = seen or set()
        for node in cls.body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == attr:
                return node, modname, f
            if isinstance(node, (ast.Assign, ast.AnnAssign)):
                targets = node.targets if isinstance(node, ast.Assign) else [node.target]
                if any(isinstance(t, ast.Name) and t.id == attr for t in targets):
                    return node, modname, f
        for b in self.bases(cls, modname, f):
            key = (b[1], b[0].name)
            if key in seen:
                continue
            seen.add(key)
            r = self.class_member(b[0], b[1], b[2], attr, seen)
            if r:
                return r
        return None

    def members(self, cls, modname, f, inherited: bool, seen=None):
        """Ordered public members: name -> (node, modname, file)."""
        seen = seen if seen is not None else set()
        out: dict[str, tuple] = {}
        body = list(cls.body)
        for i, node in enumerate(body):
            name = None
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                name = node.name
            elif isinstance(node, (ast.Assign, ast.AnnAssign)):
                targets = node.targets if isinstance(node, ast.Assign) else [node.target]
                t = targets[0]
                if isinstance(t, ast.Name):
                    name = t.id
                    # attribute docstring: a string expression right after
                    nxt = body[i + 1] if i + 1 < len(body) else None
                    if not (isinstance(nxt, ast.Expr) and isinstance(getattr(nxt, "value", None), ast.Constant)
                            and isinstance(nxt.value.value, str)):
                        continue
                    node = (node, nxt.value.value)
            if not name or name.startswith("_") or name in out:
                continue
            out[name] = (node, modname, f)
        if inherited:
            for b in self.bases(cls, modname, f):
                key = (b[1], b[0].name)
                if key in seen:
                    continue
                seen.add(key)
                for k, v in self.members(b[0], b[1], b[2], True, seen).items():
                    out.setdefault(k, v)
        return out


def node_doc(node) -> str:
    if isinstance(node, tuple):           # (assign, attribute docstring)
        return node[1]
    if isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
        return ast.get_docstring(node) or ""
    return ""


def node_signature(name: str, node) -> str:
    if isinstance(node, tuple):
        node = node[0]
    if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
        args = []
        a = node.args
        pos = a.posonlyargs + a.args
        defaults = [None] * (len(pos) - len(a.defaults)) + list(a.defaults)
        for arg, d in zip(pos, defaults):
            if arg.arg in ("self", "cls"):
                continue
            args.append(arg.arg + ("=" + _short(d) if d is not None else ""))
        if a.vararg:
            args.append("*" + a.vararg.arg)
        for arg, d in zip(a.kwonlyargs, a.kw_defaults):
            args.append(arg.arg + ("=" + _short(d) if d is not None else ""))
        if a.kwarg:
            args.append("**" + a.kwarg.arg)
        return f"{name}({', '.join(args)})"
    return name


def _short(d) -> str:
    s = ast.unparse(d)
    return s if len(s) < 30 else "..."


def is_property(node) -> bool:
    if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
        return any(ast.unparse(d).split(".")[-1] in ("property", "cached_property") for d in node.decorator_list)
    return False


def fastapi_param_docs(node) -> list[tuple[str, str]]:
    """FastAPI documents parameters as Annotated[T, Doc("...")]."""
    out = []
    if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
        return out
    a = node.args
    for arg in a.posonlyargs + a.args + a.kwonlyargs:
        ann = arg.annotation
        if isinstance(ann, ast.Subscript) and ast.unparse(ann.value).endswith("Annotated"):
            elts = ann.slice.elts if isinstance(ann.slice, ast.Tuple) else []
            for e in elts[1:]:
                if isinstance(e, ast.Call) and ast.unparse(e.func).endswith("Doc") and e.args:
                    v = e.args[0]
                    if isinstance(v, ast.Constant) and isinstance(v.value, str):
                        out.append((arg.arg, " ".join(v.value.split())))
    return out


