# ----------------------------------------------------------------------------
# FastAPI (Markdown)
# ----------------------------------------------------------------------------

FASTAPI_INCLUDE_DIRS = ("tutorial", "advanced", "how-to", "reference", "deployment")
FASTAPI_TOP = ("index.md", "features.md", "python-types.md", "async.md",
               "fastapi-cli.md", "environment-variables.md", "virtual-environments.md",
               "alternatives.md", "history-design-future.md", "benchmarks.md")


def fastapi_pages(docs: Path) -> list[Path]:
    pages = [docs / p for p in FASTAPI_TOP if (docs / p).exists()]
    for d in FASTAPI_INCLUDE_DIRS:
        pages += sorted((docs / d).rglob("*.md"))
    return pages


def md_url(rel: Path) -> str:
    parts = list(rel.with_suffix("").parts)
    if parts[-1] == "index":
        parts = parts[:-1]
    return "/" + "/".join(parts) + ("/" if parts else "")


ADMON_RE = re.compile(r"^(/{3,})\s*(\w+)(?:\s*\|\s*(.*))?\s*$")


def fastapi_preprocess(text: str, src: Path, repo: Path, docs: Path) -> str:
    # 1. code includes  {* ../../docs_src/x/tutorial001.py hl[3] *}
    def inc(m):
        rel = m.group(1)
        p = (docs.parent / rel).resolve()  # relative to docs/en/
        if not p.exists():
            # newer layout uses _py310 / _an variants; take the best match
            cands = sorted(p.parent.glob(p.stem + "*" + p.suffix)) if p.parent.exists() else []
            p = cands[-1] if cands else None
        if p is None or not p.exists():
            return ""
        lang = {"py": "python", "html": "html", "css": "css"}.get(p.suffix[1:], "")
        return f"\n```{lang}\n{p.read_text(encoding='utf-8').rstrip()}\n```\n"
    text = re.sub(r"\{\*\s*(\S+)[^}]*\*\}", inc, text)
    text = re.sub(r"\{!>?\s*(\S+?)\s*!\}", inc, text)

    # 2. /// admonitions and //// tabs  ->  <div markdown="1">
    out, stack = [], []
    for line in text.split("\n"):
        m = ADMON_RE.match(line.strip())
        if m and not line.startswith("    "):
            slashes, kind, title = m.groups()
            if stack and stack[-1] == len(slashes) and not kind:
                pass
            if kind:
                stack.append(len(slashes))
                cls = "tabbed-block" if kind == "tab" else f"admonition {kind}"
                head = f'<p class="admonition-title">{html.escape(title or kind.title())}</p>'
                out.append(f'\n<div class="{cls}" markdown="1">\n{head}\n')
                continue
        if line.strip() and set(line.strip()) == {"/"} and stack:
            stack.pop()
            out.append("\n</div>\n")
            continue
        out.append(line)
    out += ["\n</div>\n"] * len(stack)
    return "\n".join(out)


def fastapi_rewrite_links(body: str, src_rel: Path) -> str:
    def fix(m):
        href = m.group(1)
        if href.startswith(("http:", "https:", "mailto:", "#")):
            return m.group(0)
        path, _, frag = href.partition("#")
        if path.endswith(".md"):
            target = (Path("/") / src_rel.parent / path)
            target = Path(os.path.normpath(target))
            url = md_url(target.relative_to("/"))
            return f'href="{url}{"#" + frag if frag else ""}"'
        return m.group(0)
    return re.sub(r'href="([^"]+)"', fix, body)


def fastapi_reference(body_md: str, si: SourceIndex) -> str:
    """Replace mkdocstrings `::: fastapi.X` blocks with rendered HTML."""
    lines = body_md.split("\n")
    out, i = [], 0
    while i < len(lines):
        m = re.match(r"^::: ([\w.]+)\s*$", lines[i])
        if not m:
            out.append(lines[i]); i += 1; continue
        name = m.group(1); i += 1
        members = None
        while i < len(lines) and (lines[i].startswith(" ") or not lines[i].strip()):
            mm = re.match(r"^\s+-\s+(\w+)", lines[i])
            if mm:
                members = (members or []) + [mm.group(1)]
            i += 1
        out.append(render_fastapi_object(name, members, si))
    return "\n".join(out)


def render_fastapi_object(name, members, si: SourceIndex) -> str:
    r = si.find(name)
    short = name.split(".")[-1]
    if r is None:
        return f'<h2 id="{name}">{short}</h2>'
    node, mod, f = r
    parts = [f'\n<div class="doc doc-object" markdown="1">\n<h2 id="{name}" class="doc doc-heading"><code>{short}</code></h2>\n']
    parts.append(_md_doc(node_doc(node), node))
    if isinstance(node, ast.ClassDef):
        mem = si.members(node, mod, f, inherited=True)
        names = members if members is not None else [k for k in mem if not k.startswith("_")]
        for mname in names:
            if mname not in mem:
                continue
            mnode = mem[mname][0]
            sig = node_signature(mname, mnode)
            parts.append(f'\n<h3 id="{name}.{mname}" class="doc doc-heading"><code>{mname}</code></h3>\n'
                         f'\n```python\n{sig}\n```\n')
            parts.append(_md_doc(node_doc(mnode), mnode))
    parts.append("\n</div>\n")
    return "".join(parts)


def _md_doc(doc: str, node) -> str:
    doc = doc or ""
    # docstring headings ("## Example") must not break the page hierarchy
    doc = re.sub(r"^#{1,6}\s+(.+)$", r"**\1**", doc, flags=re.M)
    pd = fastapi_param_docs(node[0] if isinstance(node, tuple) else node)
    if pd:
        doc += "\n\n**Parameters**\n\n" + "\n".join(f"* `{p}`: {d}" for p, d in pd)
    return "\n" + doc + "\n"


def build_fastapi(repo: Path, out: Path):
    docs = repo / "docs" / "en" / "docs"
    si = SourceIndex({"fastapi": repo / "fastapi"})
    pages = fastapi_pages(docs)
    meta = []
    for src in pages:
        rel = src.relative_to(docs)
        text = src.read_text(encoding="utf-8")
        title_m = re.search(r"^#\s+(.+?)(\s*\{.*\})?\s*$", text, re.M)
        title = re.sub(r"[`*]", "", title_m.group(1)) if title_m else rel.stem
        meta.append((rel, md_url(rel), title))
    nav = "".join(f'<li class="md-nav__item"><a class="md-nav__link" href="{u}">{html.escape(t)}</a></li>'
                  for _, u, t in meta)
    md = markdown.Markdown(extensions=["fenced_code", "tables", "attr_list", "md_in_html", "toc", "def_list"],
                           extension_configs={"toc": {"permalink": "¶"}})
    for idx, (rel, url, title) in enumerate(meta):
        src = docs / rel
        text = fastapi_preprocess(src.read_text(encoding="utf-8"), src, repo, docs)
        if rel.parts[0] == "reference":
            text = fastapi_reference(text, si)
        md.reset()
        body = md.convert(text)
        body = fastapi_rewrite_links(body, rel).replace('href="https://fastapi.tiangolo.com/', 'href="/')
        body = body.replace("<pre><code", '<div class="highlight"><pre><code').replace("</code></pre>", "</code></pre></div>")
        prev_ = meta[idx - 1] if idx > 0 else None
        next_ = meta[idx + 1] if idx + 1 < len(meta) else None
        pn = ""
        if prev_:
            pn += f'<a href="{prev_[1]}" class="md-footer__link--prev">Previous: {html.escape(prev_[2])}</a>'
        if next_:
            pn += f'<a href="{next_[1]}" class="md-footer__link--next">Next: {html.escape(next_[2])}</a>'
        page = FASTAPI_TEMPLATE.format(title=html.escape(title), path=url, nav=nav, body=body, prevnext=pn)
        dest = out / "fastapi" / url.strip("/") / "index.html"
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(page, encoding="utf-8")
    (out / "fastapi" / "robots.txt").write_text("User-agent: *\nDisallow: /search/\n")
    print(f"fastapi: {len(meta)} pages")


