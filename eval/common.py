"""
Shared evaluation code: queries, relevance judgments, metrics, significance.

Relevance scale: 0 not relevant, 1 partially relevant / related, 2 answers the query.

Where judgments come from (first file that exists wins):
  1. eval/qrels.tsv          merged human judgments of the pooled results
                             (python -m eval.pool, then eval.judge, then eval.merge)
  2. eval/qrels_author.tsv   provisional judgments derived from the gold
                             patterns written with each query (eval/queries.jsonl).
                             Generated by `python -m eval.pool`. They cover every
                             matching chunk in the collection, not just pooled ones.

Metrics (binary relevance = grade >= 1; nDCG uses graded gain 2^g - 1):
  P@k, recall@k, AP (MAP), RR (MRR), nDCG@10, judged@10 (fraction of the top 10 judged).
"""
from __future__ import annotations

import fnmatch
import hashlib
import json
import math
from collections import defaultdict
from pathlib import Path

import numpy as np

EVAL_DIR = Path(__file__).resolve().parent
RESULTS = EVAL_DIR / "results"


def load_queries(path: Path = EVAL_DIR / "queries.jsonl") -> list[dict]:
    with open(path, encoding="utf-8") as f:
        return [json.loads(l) for l in f if l.strip()]


def split_of(q: dict) -> str:
    """Deterministic, type-stratified split: one third dev, two thirds test."""
    h = int(hashlib.md5(q["qid"].encode()).hexdigest(), 16)
    return "dev" if h % 3 == 0 else "test"


def splits(queries: list[dict]) -> dict[str, list[dict]]:
    out = {"dev": [], "test": []}
    for q in queries:
        out[split_of(q)].append(q)
    return out


def author_qrels(queries: list[dict], chunk_ids: list[str]) -> dict[str, dict[str, int]]:
    qrels: dict[str, dict[str, int]] = {}
    for q in queries:
        rel: dict[str, int] = {}
        for grade in ("1", "2"):
            for pat in q["gold"].get(grade, []):
                for cid in fnmatch.filter(chunk_ids, pat):
                    rel[cid] = max(rel.get(cid, 0), int(grade))
        qrels[q["qid"]] = rel
    return qrels


def read_qrels(path: Path) -> dict[str, dict[str, int]]:
    qrels: dict[str, dict[str, int]] = defaultdict(dict)
    with open(path, encoding="utf-8") as f:
        for line in f:
            if not line.strip() or line.startswith("#"):
                continue
            qid, cid, g = line.rstrip("\n").split("\t")[:3]
            qrels[qid][cid] = int(g)
    return dict(qrels)


def write_qrels(qrels: dict[str, dict[str, int]], path: Path, header: str = ""):
    with open(path, "w", encoding="utf-8") as f:
        if header:
            f.write("".join(f"# {l}\n" for l in header.splitlines()))
        for qid in sorted(qrels):
            for cid, g in sorted(qrels[qid].items()):
                f.write(f"{qid}\t{cid}\t{g}\n")


def load_qrels() -> tuple[dict[str, dict[str, int]], str]:
    human = EVAL_DIR / "qrels.tsv"
    if human.exists():
        return read_qrels(human), "human (pooled)"
    auth = EVAL_DIR / "qrels_author.tsv"
    if auth.exists():
        return read_qrels(auth), "provisional (author gold patterns)"
    raise FileNotFoundError("no judgments: run `python -m eval.pool` first")


# ---------------- metrics ----------------

def per_query_metrics(ranked: list[str], rel: dict[str, int], judged: set[str] | None = None,
                      k: int = 10) -> dict[str, float]:
    binrel = {d for d, g in rel.items() if g >= 1}
    R = len(binrel)
    hits = [1 if d in binrel else 0 for d in ranked]
    out = {}
    for kk in (1, 3, 5, 10):
        out[f"P@{kk}"] = sum(hits[:kk]) / kk
    out["R@10"] = sum(hits[:10]) / R if R else 0.0
    out["R@100"] = sum(hits[:100]) / R if R else 0.0
    ap, h = 0.0, 0
    for i, x in enumerate(hits, 1):
        if x:
            h += 1
            ap += h / i
    out["AP"] = ap / R if R else 0.0
    out["RR"] = next((1.0 / i for i, x in enumerate(hits, 1) if x), 0.0)
    dcg = sum((2 ** rel.get(d, 0) - 1) / math.log2(i + 1) for i, d in enumerate(ranked[:k], 1))
    ideal = sorted(rel.values(), reverse=True)[:k]
    idcg = sum((2 ** g - 1) / math.log2(i + 1) for i, g in enumerate(ideal, 1))
    out["nDCG@10"] = dcg / idcg if idcg else 0.0
    if judged is not None:
        out["judged@10"] = sum(1 for d in ranked[:10] if d in judged) / max(1, min(10, len(ranked)))
    return out


def evaluate(run: dict[str, list[str]], qrels: dict[str, dict[str, int]], qids: list[str],
             judged: dict[str, set[str]] | None = None) -> tuple[dict[str, float], dict[str, dict]]:
    per = {}
    for qid in qids:
        per[qid] = per_query_metrics(run.get(qid, []), qrels.get(qid, {}),
                                     judged.get(qid) if judged else None)
    keys = next(iter(per.values())).keys() if per else []
    mean = {k: float(np.mean([per[q][k] for q in per])) for k in keys}
    mean = {("MAP" if k == "AP" else "MRR" if k == "RR" else k): v for k, v in mean.items()}
    return mean, per


# ---------------- significance ----------------

def paired_bootstrap(a: list[float], b: list[float], n: int = 10000, seed: int = 0) -> float:
    """Two-sided p-value that mean(b - a) differs from 0 (paired bootstrap)."""
    rng = np.random.default_rng(seed)
    d = np.asarray(b) - np.asarray(a)
    if np.allclose(d, 0):
        return 1.0
    obs = d.mean()
    centered = d - obs
    idx = rng.integers(0, len(d), size=(n, len(d)))
    boot = centered[idx].mean(1)
    return float((np.abs(boot) >= abs(obs)).mean())


def wilcoxon_p(a: list[float], b: list[float]) -> float:
    from scipy.stats import wilcoxon
    d = np.asarray(b) - np.asarray(a)
    if np.allclose(d, 0):
        return 1.0
    try:
        return float(wilcoxon(a, b, zero_method="wilcox").pvalue)
    except ValueError:
        return 1.0


def compare(per_a: dict, per_b: dict, metric: str = "nDCG@10") -> dict:
    qids = sorted(set(per_a) & set(per_b))
    a = [per_a[q][metric] for q in qids]
    b = [per_b[q][metric] for q in qids]
    return {"delta": float(np.mean(b) - np.mean(a)), "p_bootstrap": paired_bootstrap(a, b),
            "p_wilcoxon": wilcoxon_p(a, b), "wins": int(sum(y > x for x, y in zip(a, b))),
            "losses": int(sum(y < x for x, y in zip(a, b))), "n": len(qids)}


def cohen_kappa(x: list[int], y: list[int], labels=(0, 1, 2), weights: str | None = None) -> float:
    """Cohen's kappa (unweighted, or 'linear' weighted for the ordinal 0/1/2 scale)."""
    L = len(labels)
    pos = {l: i for i, l in enumerate(labels)}
    O = np.zeros((L, L))
    for a, b in zip(x, y):
        O[pos[a], pos[b]] += 1
    n = O.sum()
    if n == 0:
        return float("nan")
    E = np.outer(O.sum(1), O.sum(0)) / n
    if weights == "linear":
        W = np.abs(np.subtract.outer(np.arange(L), np.arange(L))) / (L - 1)
    else:
        W = 1 - np.eye(L)
    denom = (W * E).sum()
    return float(1 - (W * O).sum() / denom) if denom else 1.0


def fmt_table(rows: list[dict], cols: list[str], floatfmt: str = ".3f") -> str:
    head = "| " + " | ".join(cols) + " |"
    sep = "|" + "|".join(":---" if i == 0 else "---:" for i in range(len(cols))) + "|"
    lines = [head, sep]
    for r in rows:
        cells = []
        for c in cols:
            v = r.get(c, "")
            cells.append(format(v, floatfmt) if isinstance(v, float) else str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)
